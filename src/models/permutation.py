"""Participant-level label-swap permutation test for the left/right classifier.

Hypothesis tested (one-sided): leave-one-participant-out accuracy is higher than expected if the leg label carries
no information about a recording's features *beyond the participant it belongs to*.

What is permuted
----------------
Each participant contributes exactly one left and one right recording. Under H0 the two leg labels of a participant
are exchangeable, so the null distribution is generated by swapping left<->right for a *whole participant* (all
windows of both recordings at once): ``y_perm = 1 - y`` for the swapped participants, ``y`` otherwise. This

* keeps every window's features and participant membership unchanged (participant effects, window dependence and
  recording structure are preserved, only the leg label is reassigned);
* keeps each participant's class balance (swap of a balanced participant is balanced);
* is applied to training AND test labels in every fold, and the full leave-one-participant-out procedure (scaler +
  classifier) is re-fitted for each permutation, so the null includes the fitting procedure.

With n participants there are exactly 2**n distinct swap patterns (4096 for 12). When 2**n <= ``exact_max`` ALL
patterns are enumerated (including the identity, which reproduces the observed statistic) and the p-value is exact:
``p = #{null >= observed} / 2**n`` (the identity guarantees p >= 1/2**n). Otherwise random patterns are drawn with a
seeded generator and the Monte Carlo convention ``p = (b + 1) / (B + 1)`` is used, in which the observed statistic is
counted as one of the permutations. Both are one-sided (upper tail) with a 1e-12 tolerance for floating-point ties.

Assumptions and limits
----------------------
Exchangeability of a participant's two recordings requires that nothing systematic other than the leg label
(recording order, fatigue, re-mounting, orientation) differs between them; the leg order is unknown here, and mounting
is part of what "leg" means in this design, so a small p-value would not prove biological asymmetry.
"""
from __future__ import annotations

from itertools import product

import numpy as np
from joblib import Parallel, delayed
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import LeaveOneGroupOut
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

TOL = 1e-12


def default_model(seed: int, C: float = 1.0):
    """The classifier used throughout: standardisation + L2 logistic regression, fitted inside each training fold."""
    return make_pipeline(StandardScaler(), LogisticRegression(max_iter=3000, C=C, random_state=seed))


def logo_participant_accuracies(X: np.ndarray, y: np.ndarray, groups: np.ndarray, make_model) -> tuple[np.ndarray, list]:
    """Leave-one-participant-out accuracy per held-out participant (mean over that participant's windows)."""
    accs, order = [], []
    for tr, te in LeaveOneGroupOut().split(X, y, groups):
        assert not (set(groups[tr]) & set(groups[te])), "participant appears in both training and test data"
        m = make_model().fit(X[tr], y[tr])
        accs.append(float((m.predict(X[te]) == y[te]).mean()))
        order.append(groups[te][0])
    return np.array(accs), order


def swap_patterns(n_groups: int, n_perm: int | None, rng: np.random.Generator | None, exact_max: int = 5000
                  ) -> tuple[np.ndarray, bool]:
    """Boolean (B, n_groups) matrix of participant swap indicators and whether it is the exhaustive set.

    ``n_perm=None`` requests exact enumeration; it is used when 2**n_groups <= exact_max, otherwise ``n_perm`` is required.
    """
    if n_perm is None or (2 ** n_groups <= exact_max and n_perm >= 2 ** n_groups):
        if 2 ** n_groups > exact_max:
            raise ValueError(f"{n_groups} groups: {2 ** n_groups} patterns exceed exact_max={exact_max}; give n_perm")
        return np.array(list(product([False, True], repeat=n_groups)), dtype=bool), True
    if rng is None:
        raise ValueError("a numpy Generator is required for Monte Carlo permutations")
    return rng.random((n_perm, n_groups)) < 0.5, False


def apply_swaps(y: np.ndarray, group_index: np.ndarray, swap: np.ndarray) -> np.ndarray:
    """Swap left/right labels of every window belonging to a swapped participant."""
    return np.where(swap[group_index], 1 - y, y)


def _one(X, y, groups, group_index, swap, make_model) -> float:
    yp = apply_swaps(y, group_index, swap)
    return float(logo_participant_accuracies(X, yp, groups, make_model)[0].mean())


def permutation_null(X, y, groups, make_model, patterns: np.ndarray, n_jobs: int = -1) -> np.ndarray:
    """Mean participant accuracy for every swap pattern (full LOGO re-fit each time)."""
    uniq, group_index = np.unique(groups, return_inverse=True)
    if patterns.shape[1] != len(uniq):
        raise ValueError("patterns must have one column per participant")
    out = Parallel(n_jobs=n_jobs)(delayed(_one)(X, y, groups, group_index, p, make_model) for p in patterns)
    return np.array(out)


def permutation_pvalue(observed: float, null: np.ndarray, exact: bool) -> float:
    """One-sided (upper-tail) permutation p-value; see the module docstring for the two conventions."""
    b = int((np.asarray(null) >= observed - TOL).sum())
    return b / len(null) if exact else (b + 1) / (len(null) + 1)


def random_guess_distribution(groups: np.ndarray, n_sim: int, rng: np.random.Generator) -> np.ndarray:
    """Mean participant accuracy of a classifier that guesses each window independently with p = 0.5 (balanced classes).

    Its spread is binomial (about 0.03 for 12 participants x 18 windows) because it involves no model fitting and no
    window dependence; the permutation null (which re-fits the model on swapped labels) is the appropriate reference for
    a fitted model and can be wider (compare the two SDs in the audit outputs). A single random-guess draw is not a
    meaningful baseline.
    """
    uniq, idx = np.unique(groups, return_inverse=True)
    n = np.bincount(idx)
    return np.array([np.mean([(rng.random(k) < 0.5).mean() for k in n]) for _ in range(n_sim)])
